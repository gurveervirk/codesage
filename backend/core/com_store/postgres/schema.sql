CREATE OR REPLACE FUNCTION resolve_external_relations_on_entity()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ext_rel RECORD;
BEGIN
    FOR ext_rel IN
        SELECT id, from_entity_id, rel_type, attributes
        FROM relations
        WHERE to_entity_name = NEW.name
          AND to_entity_id IS NULL
    LOOP
        IF EXISTS (
            SELECT 1 FROM relations
            WHERE from_entity_id = ext_rel.from_entity_id
              AND to_entity_id = NEW.id
              AND rel_type = ext_rel.rel_type
        ) THEN
            UPDATE relations
            SET attributes = attributes || ext_rel.attributes
            WHERE from_entity_id = ext_rel.from_entity_id
              AND to_entity_id = NEW.id
              AND rel_type = ext_rel.rel_type;
            DELETE FROM relations WHERE id = ext_rel.id;
        ELSE
            UPDATE relations
            SET to_entity_id = NEW.id,
                to_entity_name = NULL
            WHERE id = ext_rel.id;
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_entities_resolve_externals
AFTER INSERT ON entities
FOR EACH ROW EXECUTE FUNCTION resolve_external_relations_on_entity();

CREATE OR REPLACE FUNCTION resolve_external_relations_on_alias()
RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    ext_rel RECORD;
BEGIN
    FOR ext_rel IN
        SELECT id, from_entity_id, rel_type, attributes
        FROM relations
        WHERE to_entity_name = NEW.alias
          AND to_entity_id IS NULL
    LOOP
        IF EXISTS (
            SELECT 1 FROM relations
            WHERE from_entity_id = ext_rel.from_entity_id
              AND to_entity_id = NEW.entity_id
              AND rel_type = ext_rel.rel_type
        ) THEN
            UPDATE relations
            SET attributes = attributes || ext_rel.attributes
            WHERE from_entity_id = ext_rel.from_entity_id
              AND to_entity_id = NEW.entity_id
              AND rel_type = ext_rel.rel_type;
            DELETE FROM relations WHERE id = ext_rel.id;
        ELSE
            UPDATE relations
            SET to_entity_id = NEW.entity_id,
                to_entity_name = NULL
            WHERE id = ext_rel.id;
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_aliases_resolve_externals
AFTER INSERT ON aliases
FOR EACH ROW EXECUTE FUNCTION resolve_external_relations_on_alias();

CREATE TABLE module_symbols (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    symbol_name TEXT NOT NULL,
    origin TEXT NOT NULL,
    entity_id BIGINT REFERENCES entities(id) ON DELETE SET NULL,
    source_fqn TEXT,
    condition TEXT,
    line_no INTEGER,
    parent_block_start_line INTEGER,
    is_reexport BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE UNIQUE INDEX idx_module_symbols_unique ON module_symbols (module_entity_id, symbol_name, COALESCE(condition, ''));
CREATE INDEX idx_module_symbols_module ON module_symbols (module_entity_id);
CREATE INDEX idx_module_symbols_entity ON module_symbols (entity_id);
CREATE INDEX idx_module_symbols_source_fqn ON module_symbols (source_fqn);

CREATE TABLE module_symbol_versions (
    module_symbol_id BIGINT NOT NULL REFERENCES module_symbols(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    PRIMARY KEY (module_symbol_id, version_id)
);
CREATE INDEX idx_module_symbol_versions_version ON module_symbol_versions (version_id);

CREATE TABLE alias_hops (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    alias_id BIGINT NOT NULL REFERENCES aliases(id) ON DELETE CASCADE,
    hop_order INTEGER NOT NULL,
    module_source_id BIGINT REFERENCES module_sources(id) ON DELETE SET NULL,
    line_no INTEGER,
    target_entity_id BIGINT REFERENCES entities(id) ON DELETE SET NULL,
    target_entity_name TEXT,
    UNIQUE (alias_id, hop_order),
    CHECK (
        (target_entity_id IS NOT NULL AND target_entity_name IS NULL)
        OR (target_entity_id IS NULL AND target_entity_name IS NOT NULL)
        OR (target_entity_id IS NULL AND target_entity_name IS NULL)
    )
);
CREATE INDEX idx_alias_hops_alias ON alias_hops (alias_id);
CREATE INDEX idx_alias_hops_target_entity ON alias_hops (target_entity_id);
CREATE INDEX idx_alias_hops_target_name ON alias_hops (target_entity_name);

CREATE TABLE alias_hop_versions (
    alias_hop_id BIGINT NOT NULL REFERENCES alias_hops(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    PRIMARY KEY (alias_hop_id, version_id)
);
CREATE INDEX idx_alias_hop_versions_version ON alias_hop_versions (version_id);

CREATE OR REPLACE FUNCTION resolve_alias_hops_on_entity()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    UPDATE alias_hops
    SET target_entity_id = NEW.id,
        target_entity_name = NULL
    WHERE target_entity_name = NEW.name
      AND target_entity_id IS NULL;
    RETURN NEW;
END;
$$;

CREATE TRIGGER trg_alias_hops_resolve_on_entity
AFTER INSERT ON entities
FOR EACH ROW EXECUTE FUNCTION resolve_alias_hops_on_entity();
