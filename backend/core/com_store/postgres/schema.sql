CREATE TABLE versions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version_text TEXT NOT NULL UNIQUE
);

CREATE TABLE entities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    types TEXT[] NOT NULL DEFAULT '{}',
    meta_labels TEXT[] NOT NULL DEFAULT '{}',
    path ltree
);
CREATE INDEX idx_entities_types ON entities USING GIN (types);
CREATE INDEX idx_entities_meta_labels ON entities USING GIN (meta_labels);
CREATE INDEX idx_entities_path_gist ON entities USING GIST (path);

CREATE TABLE entity_versions (
    entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    PRIMARY KEY (entity_id, version_id)
);
CREATE INDEX idx_entity_versions_version ON entity_versions (version_id);

CREATE TABLE module_sources (
