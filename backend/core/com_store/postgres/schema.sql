-- Enable GIN index support for scalar types if needed (usually standard GIN works for arrays)
CREATE EXTENSION IF NOT EXISTS btree_gin;

-- 1. Logical Entities (The "Nodes")
-- Represents the existence of a Code Object (Class, Func, Module) regardless of version.
CREATE TABLE IF NOT EXISTS entities (
    name TEXT PRIMARY KEY,          -- Fully Qualified Name (e.g. 'package.module.Class')
    type TEXT NOT NULL,             -- 'CLASS', 'FUNCTION', 'MODULE', etc.
    meta_labels TEXT[],             -- ['public', 'generator', 'dunder', 'protected']
    versions TEXT[] NOT NULL DEFAULT '{}'       -- All versions this entity exists in
);

-- Optimization: Partial GIN indices for fast filtered lookups by version
CREATE INDEX IF NOT EXISTS idx_entities_v_class ON entities USING GIN (versions) WHERE type = 'CLASS';
CREATE INDEX IF NOT EXISTS idx_entities_v_func ON entities USING GIN (versions) WHERE type = 'FUNCTION';
CREATE INDEX IF NOT EXISTS idx_entities_v_method ON entities USING GIN (versions) WHERE type = 'METHOD';
CREATE INDEX IF NOT EXISTS idx_entities_v_module ON entities USING GIN (versions) WHERE type = 'MODULE';
CREATE INDEX IF NOT EXISTS idx_entities_v_dist_pkg ON entities USING GIN (versions) WHERE type = 'DISTRIBUTION_PACKAGE';
CREATE INDEX IF NOT EXISTS idx_entities_v_import_pkg ON entities USING GIN (versions) WHERE type = 'IMPORT_PACKAGE';
CREATE INDEX IF NOT EXISTS idx_entities_type ON entities (type);
CREATE INDEX IF NOT EXISTS idx_entities_meta_labels ON entities USING GIN (meta_labels);

-- 2. Entity Definitions (The "Properties" that change over time)
-- One entity can have multiple rows here if its code changes across versions.
-- Using content_hash as the Primary Key since it uniquely identifies the state of the entity (Name + Props).
CREATE TABLE IF NOT EXISTS sources (
    content_hash TEXT PRIMARY KEY,  -- Deduplication key (Name + Source)
    entity_name TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    source_code TEXT,
    docstring TEXT,
    signature TEXT,                 -- The raw signature from source
    attributes JSONB DEFAULT '{}'::jsonb, -- Extra attributes
    versions TEXT[] NOT NULL DEFAULT '{}' -- Versions sharing THIS specific source content
);
-- We still need an index on entity_name to quickly find "all sources for Class X"
CREATE INDEX IF NOT EXISTS idx_sources_entity_name ON sources (entity_name);
CREATE INDEX IF NOT EXISTS idx_sources_versions ON sources USING GIN (versions);

-- 3. Relationships (The "Edges")
-- Relationships link Logical entities (Names), valid for specific versions.
CREATE TABLE IF NOT EXISTS relations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_entity TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    to_entity TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    rel_type TEXT NOT NULL,         -- 'INHERITS', 'CALLS', 'EXPOSES', 'PUBLISHES'
    attributes JSONB DEFAULT '{}'::jsonb, -- Relation properties (alias, etc)
    versions TEXT[] NOT NULL DEFAULT '{}',       -- Versions where this connection exists
    
    UNIQUE (from_entity, to_entity, rel_type) 
);
CREATE INDEX IF NOT EXISTS idx_rels_from ON relations (from_entity);
CREATE INDEX IF NOT EXISTS idx_rels_to ON relations (to_entity);
CREATE INDEX IF NOT EXISTS idx_rels_type ON relations (rel_type);
CREATE INDEX IF NOT EXISTS idx_rels_versions ON relations USING GIN (versions);

-- 4. Import Details
CREATE TABLE IF NOT EXISTS import_details (
    content_hash TEXT PRIMARY KEY,
    entity_name TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    imports JSONB NOT NULL,         -- The import structure
    versions TEXT[] NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_import_details_entity ON import_details (entity_name);

-- 5. Resolved Signatures (if different from source signature due to typing resolution)
-- Hashes might not always be pre-computed for these, but (entity_name, resolved_sign) is unique.
CREATE TABLE IF NOT EXISTS resolved_signatures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    resolved_sign TEXT NOT NULL,
    content_hash TEXT,              -- Optional hash
    versions TEXT[] NOT NULL DEFAULT '{}',
    
    UNIQUE (entity_name, resolved_sign)
);
CREATE INDEX IF NOT EXISTS idx_resolved_sig_entity ON resolved_signatures (entity_name);

-- 6. Decorator Details
CREATE TABLE IF NOT EXISTS decorator_details (
    content_hash TEXT PRIMARY KEY,
    entity_name TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    details JSONB NOT NULL,
    versions TEXT[] NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS idx_dec_details_entity ON decorator_details (entity_name);

-- 7. Aliases
CREATE TABLE IF NOT EXISTS aliases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_name TEXT NOT NULL REFERENCES entities(name) ON DELETE CASCADE,
    alias TEXT NOT NULL,
    versions TEXT[] NOT NULL DEFAULT '{}',
    
    UNIQUE(entity_name, alias)
);
CREATE INDEX IF NOT EXISTS idx_aliases_entity ON aliases (entity_name);
CREATE INDEX IF NOT EXISTS idx_aliases_lookup ON aliases (alias);
