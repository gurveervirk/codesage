CREATE TABLE relations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    from_entity_id BIGINT NOT NULL REFERENCES entities(id) ON DELETE CASCADE,
    to_entity_id BIGINT REFERENCES entities(id) ON DELETE CASCADE,
    to_entity_name TEXT,
    rel_type TEXT NOT NULL,
    attributes JSONB NOT NULL DEFAULT '{}'::jsonb,
    CHECK (
        (to_entity_id IS NOT NULL AND to_entity_name IS NULL)
        OR (to_entity_id IS NULL AND to_entity_name IS NOT NULL)
    )
);
CREATE INDEX idx_rels_from_entity ON relations (from_entity_id);
CREATE INDEX idx_rels_to_entity ON relations (to_entity_id);
CREATE INDEX idx_rels_to_name ON relations (to_entity_name);
CREATE INDEX idx_rels_type ON relations (rel_type);
CREATE INDEX idx_rels_attributes_gin ON relations USING GIN (attributes);
CREATE UNIQUE INDEX uq_rel_internal ON relations (from_entity_id, to_entity_id, rel_type) WHERE to_entity_id IS NOT NULL;
CREATE UNIQUE INDEX uq_rel_external ON relations (from_entity_id, to_entity_name, rel_type) WHERE to_entity_id IS NULL;

CREATE TABLE relation_versions (
    relation_id BIGINT NOT NULL REFERENCES relations(id) ON DELETE CASCADE,
    version_id BIGINT NOT NULL REFERENCES versions(id) ON DELETE CASCADE,
    PRIMARY KEY (relation_id, version_id)
);
CREATE INDEX idx_relation_versions_version ON relation_versions (version_id);

